from datetime import datetime, timezone
from typing import Any

from pydantic import BaseModel, Field

from src.domain.entities.trajectory import Trajectory


class MetricResult(BaseModel):
    """Represents the outcome of a single evaluation metric applied to a SUT run."""

    metric_name: str = Field(
        ..., description="Name of the metric (e.g., Faithfulness, Groundedness)"
    )
    score: float | bool = Field(
        ..., description="Quantitative score (usually 0.0 - 1.0) or boolean status"
    )
    reasoning: str | None = Field(
        default=None, description="Detailed explanation/justification of the score"
    )
    metadata: dict[str, Any] = Field(
        default_factory=dict, description="Metadata, e.g., LLM judge token usage or timing"
    )


class TestCaseEvaluation(BaseModel):
    """The evaluation results for a single test case execution."""

    __test__ = False  # Prevent Pytest from trying to collect this as a test class

    case_id: str = Field(..., description="ID of the associated GoldenTestCase")
    trajectory: Trajectory = Field(
        ..., description="The trajectory generated by the SUT during the test"
    )
    metrics: dict[str, MetricResult] = Field(
        default_factory=dict, description="Calculated metric results"
    )
    success: bool = Field(
        ..., description="Overall boolean status indicating whether this test passed its thresholds"
    )
    evaluated_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc), description="Evaluation timestamp"
    )


class EvaluationRun(BaseModel):
    """Represents a full evaluation suite execution over a dataset."""

    run_id: str = Field(..., description="Unique run identifier")
    dataset_id: str = Field(..., description="ID of the golden dataset evaluated")
    dataset_version: str = Field(..., description="Version of the golden dataset evaluated")
    sut_version: str = Field(..., description="Version of the SUT under evaluation")
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc), description="Run start timestamp"
    )
    cases: list[TestCaseEvaluation] = Field(
        default_factory=list, description="Evaluations of individual cases"
    )
    parameters: dict[str, Any] = Field(
        default_factory=dict, description="Evaluation run parameters/configs"
    )
    summary: dict[str, Any] = Field(
        default_factory=dict, description="Aggregated statistics (e.g., success_rate, avg_cost)"
    )
    metadata: dict[str, Any] = Field(default_factory=dict, description="Arbitrary run metadata")

    def compute_summary(self) -> None:
        """Aggregates scores from individual cases to compute a run summary."""
        if not self.cases:
            self.summary = {
                "total_cases": 0,
                "successful_cases": 0,
                "success_rate": 0.0,
                "avg_latency": 0.0,
                "total_cost": 0.0,
                "total_tokens": 0,
            }
            return

        total_cases = len(self.cases)
        successful_cases = sum(1 for c in self.cases if c.success)
        success_rate = successful_cases / total_cases

        total_sec = 0.0
        total_usd = 0.0
        total_tokens = 0

        metric_sums: dict[str, float] = {}
        metric_counts: dict[str, int] = {}

        for case in self.cases:
            total_sec += case.trajectory.total_latency.seconds
            total_usd += case.trajectory.total_cost.amount
            total_tokens += case.trajectory.total_token_usage.total_tokens

            for m_name, m_res in case.metrics.items():
                if isinstance(m_res.score, (int, float)):
                    metric_sums[m_name] = metric_sums.get(m_name, 0.0) + float(m_res.score)
                    metric_counts[m_name] = metric_counts.get(m_name, 0) + 1

        avg_metrics = {
            m_name: metric_sums[m_name] / metric_counts[m_name] for m_name in metric_sums
        }

        self.summary = {
            "total_cases": total_cases,
            "successful_cases": successful_cases,
            "success_rate": success_rate,
            "avg_latency": total_sec / total_cases,
            "total_cost": total_usd,
            "total_tokens": total_tokens,
            "avg_metrics": avg_metrics,
        }
